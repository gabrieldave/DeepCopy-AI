package com.blackeye.klipnote

import android.content.Context
import android.webkit.CookieManager
import androidx.annotation.Keep
import java.io.File
import java.net.URI

/**
 * Sitios donde el usuario puede conectar SU PROPIA sesión para descargas que piden login.
 * Las cookies de cada usuario se quedan en su teléfono; nunca se publican cookies en el repo.
 */
@Keep
enum class CookieSite(
    val label: String,
    /** Dominio con el que se escriben las líneas Netscape (yt-dlp hace match por dominio). */
    val domain: String,
    val loginUrl: String,
    /** URLs de las que se leen cookies en el CookieManager del WebView. */
    val cookieUrls: List<String>,
    /** Hosts que identifican un enlace de este sitio. */
    val hosts: List<String>,
    /** Aviso específico del sitio (o null). */
    val note: String? = null
) {
    INSTAGRAM(
        label = "Instagram",
        domain = ".instagram.com",
        loginUrl = "https://www.instagram.com/accounts/login/",
        cookieUrls = listOf(
            "https://www.instagram.com/",
            "https://instagram.com/",
            "https://m.instagram.com/",
            "https://www.instagram.com/accounts/login/"
        ),
        hosts = listOf("instagram.com", "instagr.am", "cdninstagram.com")
    ),
    YOUTUBE(
        label = "YouTube",
        domain = ".youtube.com",
        loginUrl = "https://accounts.google.com/ServiceLogin?service=youtube&continue=https%3A%2F%2Fm.youtube.com%2F",
        cookieUrls = listOf(
            "https://www.youtube.com/",
            "https://m.youtube.com/",
            "https://youtube.com/"
        ),
        hosts = listOf("youtube.com", "youtu.be", "youtube-nocookie.com")
    ),
    TIKTOK(
        label = "TikTok",
        domain = ".tiktok.com",
        loginUrl = "https://www.tiktok.com/login",
        cookieUrls = listOf("https://www.tiktok.com/", "https://m.tiktok.com/"),
        hosts = listOf("tiktok.com")
    ),
    FACEBOOK(
        label = "Facebook",
        domain = ".facebook.com",
        loginUrl = "https://m.facebook.com/login/",
        cookieUrls = listOf("https://www.facebook.com/", "https://m.facebook.com/"),
        hosts = listOf("facebook.com", "fb.watch", "fb.com")
    ),
    X(
        label = "X / Twitter",
        domain = ".x.com",
        loginUrl = "https://x.com/i/flow/login",
        cookieUrls = listOf("https://x.com/", "https://twitter.com/"),
        hosts = listOf("x.com", "twitter.com")
    );

    val fileName: String get() = "cookies_${name.lowercase()}.txt"
}

/**
 * Cookies Netscape locales (estilo Seal) para yt-dlp `--cookies`, un archivo por sitio.
 * Solo en [Context.getFilesDir] (allowBackup=false); nunca se suben.
 * A yt-dlp solo se le pasa el archivo del sitio del enlace que se descarga.
 */
object CookieStore {
    private const val PREFS = "klipnote_cookies"
    private const val KEY_ENABLED = "cookies_enabled"
    private const val KEY_USER_AGENT = "cookies_user_agent"
    private const val LEGACY_FILE_NAME = "cookies.txt"

    const val COOKIE_HEADER =
        "# Netscape HTTP Cookie File\n# Auto-generated by KlipNote WebView\n"

    fun cookiesFile(context: Context, site: CookieSite): File =
        File(context.applicationContext.filesDir, site.fileName)

    /** Mueve el cookies.txt antiguo (solo Instagram) al nuevo esquema por sitio. */
    fun migrateLegacy(context: Context) {
        runCatching {
            val legacy = File(context.applicationContext.filesDir, LEGACY_FILE_NAME)
            val target = cookiesFile(context, CookieSite.INSTAGRAM)
            if (legacy.isFile && !target.exists()) {
                if (!legacy.renameTo(target)) {
                    legacy.copyTo(target, overwrite = true)
                    legacy.delete()
                }
            }
        }
    }

    fun hasCookies(context: Context, site: CookieSite): Boolean {
        val f = cookiesFile(context, site)
        return f.isFile && f.length() > COOKIE_HEADER.length.toLong()
    }

    fun connectedSites(context: Context): List<CookieSite> =
        CookieSite.entries.filter { hasCookies(context, it) }

    /** Interruptor global «Usar cookies en descargas». */
    fun isEnabled(context: Context): Boolean =
        prefs(context).getBoolean(KEY_ENABLED, true)

    fun setEnabled(context: Context, enabled: Boolean) {
        prefs(context).edit().putBoolean(KEY_ENABLED, enabled).apply()
    }

    fun siteForUrl(url: String?): CookieSite? {
        if (url.isNullOrBlank()) return null
        val host = runCatching {
            val raw = url.trim()
            val withScheme = if (':' in raw) raw else "https://$raw"
            URI(withScheme).host?.lowercase()
        }.getOrNull() ?: return null
        return CookieSite.entries.firstOrNull { site ->
            site.hosts.any { h -> host == h || host.endsWith(".$h") }
        }
    }

    /** Archivo de cookies para el enlace dado, o null si no aplica / no hay / están apagadas. */
    fun cookiesFileFor(context: Context, url: String): File? {
        if (!isEnabled(context)) return null
        val site = siteForUrl(url) ?: return null
        val f = cookiesFile(context, site)
        return if (hasCookies(context, site)) f else null
    }

    fun userAgent(context: Context): String? =
        prefs(context).getString(KEY_USER_AGENT, null)?.takeIf { it.isNotBlank() }

    fun saveUserAgent(context: Context, userAgent: String?) {
        prefs(context).edit().putString(KEY_USER_AGENT, userAgent?.takeIf { it.isNotBlank() }).apply()
    }

    fun noteFor(context: Context, site: CookieSite): String? = when (site) {
        CookieSite.YOUTUBE -> context.getString(R.string.cookie_youtube_help)
        else -> null
    }

    fun statusLabel(context: Context, site: CookieSite): String = when {
        !hasCookies(context, site) -> context.getString(R.string.cookie_status_not_connected)
        !isEnabled(context) -> context.getString(R.string.cookie_status_connected_off)
        else -> context.getString(R.string.cookie_status_connected)
    }

    /**
     * Lee las cookies del WebView para el sitio y las escribe en formato Netscape.
     * @return cantidad de cookies guardadas.
     */
    fun saveFromCookieManager(context: Context, site: CookieSite, userAgent: String? = null): Int {
        val app = context.applicationContext
        val manager = CookieManager.getInstance()
        runCatching { manager.flush() }

        val rows = linkedMapOf<String, String>()
        for (url in site.cookieUrls) {
            val header = manager.getCookie(url) ?: continue
            parseCookieHeader(header).forEach { (name, value) -> rows[name] = value }
        }
        if (rows.isEmpty()) {
            throw IllegalStateException(
                app.getString(R.string.cookie_error_none, site.label)
            )
        }

        val body = buildString {
            append(COOKIE_HEADER)
            rows.forEach { (name, value) ->
                append(netscapeLine(site.domain, name, value))
                append('\n')
            }
        }
        cookiesFile(app, site).writeText(body)
        setEnabled(app, true)
        if (!userAgent.isNullOrBlank()) saveUserAgent(app, userAgent)
        return rows.size
    }

    /** Pega un cookies.txt Netscape (o líneas name=value) para el sitio y lo guarda en privado. */
    fun saveFromPaste(context: Context, site: CookieSite, raw: String): Int {
        val text = raw.trim()
        if (text.isBlank()) {
            throw IllegalArgumentException(context.getString(R.string.cookie_error_empty_paste))
        }

        val normalized = if (text.contains('\t') || text.contains("# Netscape")) {
            if (text.startsWith("#")) text + "\n" else COOKIE_HEADER + text.trimStart() + "\n"
        } else {
            val pairs = parseCookieHeader(text.replace('\n', ';'))
            if (pairs.isEmpty()) {
                throw IllegalArgumentException(context.getString(R.string.cookie_error_invalid))
            }
            buildString {
                append(COOKIE_HEADER)
                pairs.forEach { (name, value) ->
                    append(netscapeLine(site.domain, name, value))
                    append('\n')
                }
            }
        }

        val count = normalized.lineSequence().count { line ->
            val t = line.trim()
            t.isNotEmpty() && !t.startsWith("#") && t.contains('\t')
        }
        if (count == 0) {
            throw IllegalArgumentException(context.getString(R.string.cookie_error_invalid))
        }
        cookiesFile(context.applicationContext, site).writeText(normalized)
        setEnabled(context.applicationContext, true)
        return count
    }

    /** Borra las cookies guardadas del sitio y cierra su sesión en el WebView. */
    fun clear(context: Context, site: CookieSite) {
        runCatching { cookiesFile(context.applicationContext, site).delete() }
        runCatching {
            val manager = CookieManager.getInstance()
            for (url in site.cookieUrls) {
                val header = manager.getCookie(url) ?: continue
                parseCookieHeader(header).forEach { (name, _) ->
                    manager.setCookie(
                        url,
                        "$name=; Max-Age=0; Expires=Thu, 01 Jan 1970 00:00:00 GMT; Path=/; Domain=${site.domain}"
                    )
                    manager.setCookie(url, "$name=; Max-Age=0; Expires=Thu, 01 Jan 1970 00:00:00 GMT; Path=/")
                }
            }
            manager.flush()
        }
    }

    private fun parseCookieHeader(header: String): List<Pair<String, String>> {
        return header.split(';')
            .map { it.trim() }
            .filter { it.isNotEmpty() && it.contains('=') }
            .mapNotNull { part ->
                val eq = part.indexOf('=')
                if (eq <= 0) return@mapNotNull null
                val name = part.substring(0, eq).trim()
                val value = part.substring(eq + 1).trim()
                if (name.isEmpty()) null else name to value
            }
    }

    private fun netscapeLine(domain: String, name: String, value: String): String {
        // domain \t includeSubdomains \t path \t secure \t expiry \t name \t value
        return listOf(domain, "TRUE", "/", "TRUE", "0", name, value).joinToString("\t")
    }

    private fun prefs(context: Context) =
        context.applicationContext.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
}
